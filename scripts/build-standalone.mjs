// Builds the single-file website:  node scripts/build-standalone.mjs
// Packs web/index.html + css + every ES module (entry: web/js/standalone.js) into standalone/OnlineExamSystem.html.
// The result needs no server: double-click it. (Modules are wrapped in plain functions because browsers refuse to load
// ES modules from file:// URLs.) No third-party tools are used.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, relative, resolve, posix } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const webDir = join(root, 'web');
const entry = 'js/standalone.js';

const modules = new Map();      // id -> transformed code

function normalize(id) { return posix.normalize(id); }

function visit(id) {
  if (modules.has(id)) return;
  modules.set(id, null);        // mark as seen (guards against cycles)
  let code = readFileSync(join(webDir, id), 'utf8');
  const exportsList = [];
  const aliasExports = [];

  code = code.replace(/^import\s+(?:\{([^}]*)\}\s+from\s+)?['"]([^'"]+)['"];?[ \t]*$/gm, (m, names, spec) => {
    const dep = normalize(posix.join(posix.dirname(id), spec));
    visit(dep);
    if (!names) return `__require(${JSON.stringify(dep)});`;
    const list = names.split(',').map((s) => s.trim()).filter(Boolean).map((s) => {
      const [a, b] = s.split(/\s+as\s+/);
      return b ? `${a}: ${b}` : a;
    });
    return `const { ${list.join(', ')} } = __require(${JSON.stringify(dep)});`;
  });
  code = code.replace(/^export\s+\{([^}]*)\};?[ \t]*$/gm, (m, names) => {
    for (const s of names.split(',').map((x) => x.trim()).filter(Boolean)) {
      const [a, b] = s.split(/\s+as\s+/);
      aliasExports.push([b || a, a]);
    }
    return '';
  });
  code = code.replace(/^export\s+(async\s+function|function|class|const|let)\s+([A-Za-z0-9_$]+)/gm, (m, kind, name) => {
    exportsList.push(name);
    return `${kind} ${name}`;
  });
  if (/^\s*(import|export)\s/m.test(code.replace(/\/\/.*$/gm, '').replace(/'[^'\n]*'|"[^"\n]*"|`[^`]*`/g, ''))) {
    throw new Error('Unsupported import/export syntax in ' + id);
  }
  const assigns = exportsList.map((n) => `__exports.${n} = ${n};`).concat(aliasExports.map(([out, inn]) => `__exports.${out} = ${inn};`));
  modules.set(id, `__define(${JSON.stringify(id)}, function (__exports, __require) {\n'use strict';\n${code}\n${assigns.join('\n')}\n});`);
}

visit(entry);

const runtime = `(function () {
'use strict';
var __defs = {}, __cache = {};
function __define(id, fn) { __defs[id] = fn; }
function __require(id) {
  if (__cache[id]) return __cache[id].exports;
  var m = { exports: {} };
  __cache[id] = m;
  if (!__defs[id]) throw new Error('Missing module ' + id);
  __defs[id](m.exports, __require);
  return m.exports;
}
${[...modules.values()].join('\n')}
__require(${JSON.stringify(entry)});
})();`;

const safeJs = runtime.replace(/<\/script/gi, '<\\/script').replace(/<!--/g, '<\\!--');
const css = readFileSync(join(webDir, 'css/style.css'), 'utf8').replace(/<\/style/gi, '<\\/style');
let html = readFileSync(join(webDir, 'index.html'), 'utf8');
const linkTag = '<link rel="stylesheet" href="css/style.css">';
const scriptTag = '<script type="module" src="js/app.js"></script>';
if (!html.includes(linkTag) || !html.includes(scriptTag)) throw new Error('web/index.html does not have the expected stylesheet/script tags');
html = html.replace(linkTag, () => `<style>\n${css}\n</style>`).replace(scriptTag, () => `<script>\n${safeJs}\n</script>`);
html = html.replace('<head>', '<head>\n  <!-- Single-file build of the Online Examination System (standalone mode). Generated by scripts/build-standalone.mjs -->');

const outDir = join(root, 'standalone');
mkdirSync(outDir, { recursive: true });
const out = join(outDir, 'OnlineExamSystem.html');
writeFileSync(out, html);
writeFileSync(join(outDir, 'index.html'), html);          // same page under the conventional name
console.log('Built ' + relative(root, out) + ' and standalone/index.html (' + Math.round(html.length / 1024) + ' KB, ' + modules.size + ' modules)');
